package com.school.planner.service;

import java.util.List;

/**
 * Report from importing the school's pre-set "Calendario scolastico 2026/27"
 * (TASK-364, {@code claudedocs/spalmone-2026-27/calendario-scolastico-format.md})
 * as pinned MODA lab Lessons, plus report-only coherence cross-checks of the
 * FC/G13 and per-class day-structure sheets.
 *
 * <p>Pattern: follows {@link GoldenImportReport} (public final fields + explicit
 * constructor, nested static classes for row-level detail).</p>
 */
public class CalendarioImportReport {

    /** Whether this call was a dry run (never persists, regardless of validation outcome). */
    public final boolean dryRun;

    /**
     * Whether Lessons were actually persisted this call. False whenever
     * {@code dryRun} is true, OR whenever any {@link #modaFailures} row exists
     * (all-or-nothing: a single validation failure refuses the whole batch).
     */
    public final boolean persisted;

    /** Total data rows read from calendario_moda.csv (header excluded). */
    public final int modaRows;

    /**
     * Rows (not Lessons - one row spans {@code hours} Lessons, see
     * {@link #modaLessonsPinned}) successfully planned - only meaningful
     * together with {@link #persisted}: if false, nothing in this count was
     * actually written to the database (see the class javadoc's all-or-nothing
     * rule). Partitions {@link #modaRows} together with {@link #modaSkippedNoTimeslot}
     * and {@code modaFailures.size()}.
     */
    public final int modaPlanned;

    /**
     * Individual Lesson rows planned across every row counted in
     * {@link #modaPlanned} (a 3-hour row contributes 3) - the number of rows
     * actually persisted when {@link #persisted} is true.
     */
    public final int modaLessonsPinned;

    /**
     * Rows skipped because no Timeslot exists for their (date, slot) -
     * non-blocking (mirrors {@code GoldenImportReport#unmatchedNoTimeslot}):
     * on the current seed this is exactly the 2 calendario_moda.csv rows
     * dated after {@code TimeslotSequence.SCHOOL_YEAR_END} (2027-06-14,
     * 2027-06-15). Unlike {@link #modaFailures}, this never blocks persistence.
     */
    public final int modaSkippedNoTimeslot;

    /**
     * Rows skipped because the target course already has as many planned pins
     * as it has unpinned stub Lessons (i.e. as many hours as incarichi.csv -
     * which is Orario-aligned since TASK-371 - assigns it). "Orario wins"
     * (TASK-379): the turni sheet books whole shifts to the lab course even on
     * dates where the golden orario taught other subjects in those hours, so
     * without this cap the import would inflate the course's demand beyond
     * what the school actually scheduled (run-3 capacity analysis: +45
     * phantom hours across 1/G05). Non-blocking, like
     * {@link #modaSkippedNoTimeslot}.
     */
    public final int modaSkippedBeyondCourseHours;

    /** Per-row validation failures - teacher-initial mapping, ambiguous/missing course, calendar-closed slot, or a group/teacher conflict. All-or-nothing: any entry here blocks persistence of the whole batch (see {@link #persisted}). */
    public final List<ModaFailure> modaFailures;

    /** Total data rows read from calendario_fc.csv (header excluded). Report-only - never pinned, see class javadoc. */
    public final int FCRows;

    /** (group, date) discrepancies between calendario_fc.csv and GroupCalendarRule/StagePattern. */
    public final List<CalendarDiscrepancy> FCDiscrepancies;

    /** Total data rows read from calendario_class_days.csv (header excluded). Report-only - never pinned, see class javadoc. */
    public final int classDaysRows;

    /** (group, date) discrepancies between calendario_class_days.csv and GroupCalendarRule/StagePattern, including the StagePattern reverse check (K6). */
    public final List<CalendarDiscrepancy> classDaysDiscrepancies;

    /**
     * Per-course stub-consumption outcomes (TASK-364 code review K1): after N
     * Lessons are pinned for a MODA target course, N previously-unpinned stub
     * Lessons (rows with no timeslot yet, i.e. {@code Course.totalHours}
     * placeholders generated by {@code LessonGenerator}) are deleted so the
     * course's total Lesson count still equals {@code Course.totalHours} -
     * otherwise the solver would additionally place the leftover stubs,
     * silently doubling that course's scheduled hours. Empty whenever
     * {@link #persisted} is false (dry run, or a refused/all-or-nothing
     * batch never reaches stub consumption).
     */
    public final List<StubConsumption> stubConsumptions;

    /**
     * Pinned Lessons deleted for the MODA target courses before this call, because
     * {@code force=true} was passed and prior pins already existed (TASK-364 code
     * review K2). Always 0 unless a force re-run found something to clear. An
     * equal number of stub Lessons is always restored to compensate (see
     * {@code CalendarioImportService#refuseOrClearPriorPins}) - not tracked as
     * its own field since it's identical to this one by construction.
     */
    public final long deletedPriorPins;

    /**
     * Individual Stage-course Lesson pins PLANNED from the merged stage-ask
     * list ({@code DailyActivityQuota.stageHours} for the quota groups,
     * {@code calendario_class_days.csv}'s {@code modality=S} rows for the
     * other stage groups - TASK-381 "stage on the grid",
     * {@code CalendarioImportService#planStagePins}) - NOT sourced from the
     * golden grid. Reflects the plan, not whether it was written to the
     * database - only meaningful together with {@link #persisted}: a dry run
     * (or a refused/all-or-nothing batch) shows the same non-zero preview
     * count it would have persisted, same convention as {@link
     * #modaLessonsPinned} (NOT {@link #stubConsumptions}, which is genuinely
     * empty unless {@link #persisted} - stub consumption only ever runs
     * after a real persist, there's no "planned stub consumption" to
     * preview).
     */
    public final int stagePinned;

    /**
     * Stage lesson-hours skipped because the group's calendar had fewer open
     * slots that day than {@code stageHours} asked for (non-blocking, see
     * {@link #stagePinned}'s javadoc).
     */
    public final int stageSkippedCalendarClosed;

    /**
     * Stage lesson-hours skipped because the group's Stage course had no
     * unpinned stub Lessons left to consume (non-blocking). The "course
     * doesn't exist yet" branch behind this counter is a safety net, not a
     * normal production path since TASK-381 "stage on the grid": {@code
     * DataGenerator#generateStageCourses} now seeds every stage-eligible
     * group's Stage course at profile-creation time (maintainer 2026-07-20
     * authorization), so on any seeded 2026/27 profile this counter only
     * ever reflects genuine stub-budget exhaustion, not a missing course.
     */
    public final int stageSkippedNoBudget;

    /**
     * Stage lesson-hours on dates with no Timeslot rows at all (closures,
     * Saturdays - 280h across the 7 Stage groups): valid off-grid stage,
     * consumed at persist into {@code Course.expectedUnscheduledHours}
     * instead of being pinned. The full mechanism is owned by {@code
     * CalendarioImportService#planStagePins}' "off-grid hours draw budget
     * too" javadoc.
     */
    public final int stageOffGridHours;

    /**
     * Stage-hour ask already covered by a pinned Stage lesson of the same
     * course on that date (prior import run, or the golden import's own
     * Stage pins) - not re-planned, see {@code planStagePins}' same-course
     * idempotency javadoc.
     */
    public final int stageAlreadyPinned;

    public CalendarioImportReport(boolean dryRun, boolean persisted, int modaRows, int modaPlanned,
                                  int modaLessonsPinned, int modaSkippedNoTimeslot, int modaSkippedBeyondCourseHours, List<ModaFailure> modaFailures,
                                  int FCRows, List<CalendarDiscrepancy> FCDiscrepancies, int classDaysRows,
                                  List<CalendarDiscrepancy> classDaysDiscrepancies, List<StubConsumption> stubConsumptions,
                                  long deletedPriorPins, int stagePinned, int stageSkippedCalendarClosed, int stageSkippedNoBudget,
                                  int stageOffGridHours, int stageAlreadyPinned) {
        this.dryRun = dryRun;
        this.persisted = persisted;
        this.modaRows = modaRows;
        this.modaPlanned = modaPlanned;
        this.modaLessonsPinned = modaLessonsPinned;
        this.modaSkippedNoTimeslot = modaSkippedNoTimeslot;
        this.modaSkippedBeyondCourseHours = modaSkippedBeyondCourseHours;
        this.modaFailures = modaFailures;
        this.FCRows = FCRows;
        this.FCDiscrepancies = FCDiscrepancies;
        this.classDaysRows = classDaysRows;
        this.classDaysDiscrepancies = classDaysDiscrepancies;
        this.stubConsumptions = stubConsumptions;
        this.deletedPriorPins = deletedPriorPins;
        this.stagePinned = stagePinned;
        this.stageSkippedCalendarClosed = stageSkippedCalendarClosed;
        this.stageSkippedNoBudget = stageSkippedNoBudget;
        this.stageOffGridHours = stageOffGridHours;
        this.stageAlreadyPinned = stageAlreadyPinned;
    }

    /** One calendario_moda.csv row that failed validation (never partially applied - see {@link #persisted}). */
    public static class ModaFailure {
        public int line;
        public String date;
        public String group;
        public String initial;
        public String reason;

        public ModaFailure() {
        }

        public ModaFailure(int line, String date, String group, String initial, String reason) {
            this.line = line;
            this.date = date;
            this.group = group;
            this.initial = initial;
            this.reason = reason;
        }
    }

    /** One (group, date) coherence mismatch found in the report-only FC/class-days cross-checks. */
    public static class CalendarDiscrepancy {
        public String group;
        public String date;
        public String reason;
        public String detail;

        public CalendarDiscrepancy() {
        }

        public CalendarDiscrepancy(String group, String date, String reason, String detail) {
            this.group = group;
            this.date = date;
            this.reason = reason;
            this.detail = detail;
        }
    }

    /**
     * Stub-consumption outcome for one MODA target course (TASK-364 code
     * review K1) - see {@link #stubConsumptions}.
     */
    public static class StubConsumption {
        public String teacher;
        public String subject;
        public String group;
        /** Lessons pinned for this course by this import call. */
        public int lessonsPinned;
        /** Unpinned stub Lessons deleted to compensate ({@code <= lessonsPinned}). */
        public int consumedStubs;
        /** {@code lessonsPinned - consumedStubs} - non-zero means this course now has more total Lessons than {@code Course.totalHours} (not enough stubs pre-existed). */
        public int stubShortfall;

        public StubConsumption() {
        }

        public StubConsumption(String teacher, String subject, String group, int lessonsPinned, int consumedStubs, int stubShortfall) {
            this.teacher = teacher;
            this.subject = subject;
            this.group = group;
            this.lessonsPinned = lessonsPinned;
            this.consumedStubs = consumedStubs;
            this.stubShortfall = stubShortfall;
        }
    }
}
