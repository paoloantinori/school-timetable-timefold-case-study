package com.school.planner.rest;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.Instant;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Stream;

import jakarta.ws.rs.GET;
import jakarta.ws.rs.NotFoundException;
import jakarta.ws.rs.PathParam;
import jakarta.ws.rs.Produces;
import jakarta.ws.rs.core.MediaType;

import org.eclipse.microprofile.config.inject.ConfigProperty;

/**
 * Serves the analysis reports (the golden-vs-run comparator, the day-start
 * anatomy, any other generated HTML) from the running app, so that during
 * development they are one click away instead of a file:// URL on whichever
 * machine produced them (maintainer, 2026-07-29).
 *
 * <p>Reports are generated by the KPI scripts into the campaign directories
 * (see {@code scripts/benchmark/capture-run.sh}); this resource only lists and
 * streams what is already on disk under {@code planner.reports.dir}, newest
 * first. It is read-only and deliberately limited to {@code .html} files.</p>
 *
 * <p>Path traversal: the requested path is resolved against the root and
 * rejected unless it stays inside it, so {@code ../../etc/passwd} cannot
 * escape even though the path parameter is free-form.</p>
 */
@jakarta.ws.rs.Path("/reports")
public class ReportsResource {

    private static final DateTimeFormatter STAMP =
            DateTimeFormatter.ofPattern("dd/MM HH:mm").withZone(ZoneId.systemDefault());

    @ConfigProperty(name = "planner.reports.dir", defaultValue = "claudedocs/spalmone-2026-27")
    String reportsDir;

    /** One report on disk: repo-relative path, display name, size and last modification. */
    public record Report(String path, String name, long sizeKb, String modified) {
    }

    @GET
    @Produces(MediaType.TEXT_HTML)
    public String index() {
        StringBuilder sb = new StringBuilder("""
                <!doctype html><html lang="it"><meta charset="utf-8"><title>Report</title><style>
                body{margin:0;padding:28px;font:14px/1.6 system-ui,sans-serif;background:#fcfcfb;color:#0b0b0b}
                h1{font-size:20px;margin:0 0 4px} p{color:#52514e;margin:0 0 20px}
                table{border-collapse:collapse} td,th{text-align:left;padding:4px 18px 4px 0}
                th{font-weight:500;color:#52514e;font-size:12px}
                a{color:#2a78d6} .m{color:#52514e;font-variant-numeric:tabular-nums;font-size:12px}
                </style><h1>Report di analisi</h1>
                <p>Generati dagli script KPI e serviti da qui durante lo sviluppo. Il piu' recente in cima.</p>
                <table><tr><th>report</th><th>aggiornato</th><th>dimensione</th></tr>
                """);
        List<Report> reports = list();
        if (reports.isEmpty()) {
            sb.append("<tr><td colspan=\"3\">Nessun report in ")
              .append(escape(reportsDir))
              .append(" (generane uno con scripts/benchmark/capture-run.sh)</td></tr>");
        }
        for (Report r : reports) {
            sb.append("<tr><td><a href=\"/reports/").append(escape(r.path())).append("\">")
              .append(escape(r.name())).append("</a></td><td class=\"m\">")
              .append(r.modified()).append("</td><td class=\"m\">")
              .append(r.sizeKb()).append(" KB</td></tr>");
        }
        return sb.append("</table></html>").toString();
    }

    /** The same listing as JSON, for the frontend or a script. */
    @GET
    @jakarta.ws.rs.Path("/list")
    @Produces(MediaType.APPLICATION_JSON)
    public List<Report> list() {
        Path root = root();
        if (!Files.isDirectory(root)) {
            return List.of();
        }
        try (Stream<Path> walk = Files.walk(root)) {
            return walk.filter(p -> p.getFileName().toString().endsWith(".html"))
                    .filter(Files::isRegularFile)
                    .sorted(Comparator.comparingLong((Path p) -> p.toFile().lastModified()).reversed())
                    .map(p -> new Report(root.relativize(p).toString(),
                            root.relativize(p).toString().replace('/', ' ').replace(".html", ""),
                            p.toFile().length() / 1024,
                            STAMP.format(Instant.ofEpochMilli(p.toFile().lastModified()))))
                    .toList();
        } catch (IOException e) {
            throw new UncheckedIOException("cannot list reports under " + root, e);
        }
    }

    @GET
    @jakarta.ws.rs.Path("/{path:.+}")
    @Produces(MediaType.TEXT_HTML)
    public String report(@PathParam("path") String path) {
        Path root = root();
        Path file = root.resolve(path).normalize();
        if (!file.startsWith(root) || !path.endsWith(".html") || !Files.isRegularFile(file)) {
            throw new NotFoundException("no such report: " + path);
        }
        try {
            return Files.readString(file);
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read report " + file, e);
        }
    }

    private Path root() {
        return Paths.get(reportsDir).toAbsolutePath().normalize();
    }

    private static String escape(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }
}
