package com.school.planner.domain;

import java.time.LocalDateTime;

import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.ManyToOne;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;

@Entity
public class TeacherAvailability extends PanacheEntityBase {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    public Long id;

    @ManyToOne
    public Teacher teacher;

    public LocalDateTime startDateTime;
    public LocalDateTime endDateTime;

    @Enumerated(EnumType.STRING)
    public AvailabilityType type;

    /**
     * Non-null only for rows generated by {@code AvailabilityExpansionService}
     * from a {@link RecurringAvailabilityRule} (TASK-345) — holds that rule's
     * id. This is the delete-and-regenerate marker: re-expanding a teacher
     * deletes every row with a non-null sourceRuleId for that teacher before
     * recreating them, so stale expanded rows never linger (e.g. after a rule
     * is edited or deleted). Hand-entered availability (via the REST API or
     * seeded directly) always leaves this null and is never touched by
     * expansion.
     */
    public Long sourceRuleId;

    public TeacherAvailability() {
    }

    public TeacherAvailability(Teacher teacher, LocalDateTime startDateTime, LocalDateTime endDateTime,
                               AvailabilityType type) {
        this.teacher = teacher;
        this.startDateTime = startDateTime;
        this.endDateTime = endDateTime;
        this.type = type;
    }

    @Override
    public String toString() {
        return teacher + " " + type + " " + startDateTime + " - " + endDateTime;
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof TeacherAvailability other)) return false;
        return id != null && id.equals(other.id);
    }

    @Override
    public int hashCode() {
        return id == null ? getClass().hashCode() : id.hashCode();
    }
}
