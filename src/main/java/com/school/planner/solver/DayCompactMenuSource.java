package com.school.planner.solver;

import java.io.BufferedReader;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.jboss.logging.Logger;

import com.school.planner.domain.Course;
import com.school.planner.domain.StudentGroup;

/**
 * TASK-542 iter-20: the golden-derived BLOCK MENU for the day-compact fabricator, frozen to
 * a seed CSV with the same technique as the H-COPRESENCE depth map (TASK-452 #7: the golden
 * is a test-phase advantage and goes away; its derived facts survive as declared input).
 *
 * <p>Format ({@code seed/day-compact-menu.csv}): one row per (group, weekday, position):
 * {@code group,weekday,subject,hours}. Rows in day order define the menu's block list; the
 * fabricator places them contiguously from the group's first open slot. Generated by
 * {@code scripts/analyze/derive-day-compact-menu.py} from the golden's own day composition
 * (modal block list per (group, weekday)); regenerating the CSV is the workbook question
 * ("qual'e' il menu dei blocchi di ogni giorno") when the golden retires.
 */
public final class DayCompactMenuSource {

    private static final Logger LOG = Logger.getLogger(DayCompactMenuSource.class);

    private static final String RESOURCE = "/seed/day-compact-menu.csv";

    private DayCompactMenuSource() {
    }

    /**
     * Rows keyed by (group name, weekday): each value is the ordered block list
     * (subject, hours). Missing groups/weekdays simply have no menu (the fabricator
     * declines those days).
     */
    public record MenuRow(String group, DayOfWeek weekday, String subject, int hours) {
    }

    private static DayOfWeek parseWeekday(String token) {
        return switch (token.toUpperCase()) {
            case "MON", "MONDAY" -> DayOfWeek.MONDAY;
            case "TUE", "TUESDAY" -> DayOfWeek.TUESDAY;
            case "WED", "WEDNESDAY" -> DayOfWeek.WEDNESDAY;
            case "THU", "THURSDAY" -> DayOfWeek.THURSDAY;
            case "FRI", "FRIDAY" -> DayOfWeek.FRIDAY;
            default -> null;
        };
    }

    public static List<MenuRow> load() {
        List<MenuRow> rows = new ArrayList<>();
        try (InputStream in = DayCompactMenuSource.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                LOG.warnf("day-compact menu not found (%s): the fabricator has no menu", RESOURCE);
                return rows;
            }
            try (BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
                String line = r.readLine(); // header
                while ((line = r.readLine()) != null) {
                    if (line.isBlank() || line.startsWith("#")) {
                        continue;
                    }
                    String[] p = line.split(",");
                    if (p.length < 4) {
                        continue;
                    }
                    DayOfWeek wd = parseWeekday(p[1].trim());
                    if (wd == null) {
                        continue;
                    }
                    rows.add(new MenuRow(p[0].trim(), wd, p[2].trim(), Integer.parseInt(p[3].trim())));
                }
            }
        } catch (Exception e) {
            LOG.warnf("day-compact menu read failed (%s): %s", RESOURCE, e.getMessage());
        }
        return rows;
    }

    /** Resolve the menu rows against the seeded courses into the builder's MenuBlock lists. */
    public static Map<StudentGroup, Map<DayOfWeek, List<DayCompactBuilder.MenuBlock>>> resolve(
            List<MenuRow> rows, List<StudentGroup> groups, List<Course> courses) {
        Map<String, StudentGroup> groupByName = new LinkedHashMap<>();
        for (StudentGroup g : groups) {
            if (g.name != null) {
                groupByName.put(g.name, g);
            }
        }
        Map<String, Course> courseByGroupSubject = new LinkedHashMap<>();
        for (Course c : courses) {
            if (c.studentGroup != null && c.studentGroup.name != null && c.subject != null) {
                courseByGroupSubject.put(c.studentGroup.name + "|" + c.subject, c);
            }
        }
        Map<StudentGroup, Map<DayOfWeek, List<DayCompactBuilder.MenuBlock>>> menu = new LinkedHashMap<>();
        int unmatched = 0;
        for (MenuRow row : rows) {
            StudentGroup g = groupByName.get(row.group());
            Course c = courseByGroupSubject.get(row.group() + "|" + row.subject());
            if (g == null || c == null) {
                unmatched++;
                continue;
            }
            menu.computeIfAbsent(g, k -> new LinkedHashMap<>())
                    .computeIfAbsent(row.weekday(), k -> new ArrayList<>())
                    .add(new DayCompactBuilder.MenuBlock(c, row.hours()));
        }
        if (unmatched > 0) {
            LOG.warnf("day-compact menu: %d row(s) unmatched (group/course missing from the seed)", unmatched);
        }
        return menu;
    }

    /**
     * TASK-542 cure-1 (post-mortem iter-22): the M32 (Template deviation) reference cells
     * for the menu-covered courses, derived from the SAME menu the fabricator stamps - the
     * shared {@link DayCompactBuilder#stampDay} walk with a recording placer, over every
     * school date, so the cells are exactly the (weekday, slot) pairs the graft may place
     * (the window can vary by date, e.g. the Monday ramp, hence the union over dates).
     *
     * <p>The iter-22 gate measured M32 fighting the fabricator (-978k on 7923 lessons)
     * because the reference came from {@code WeeklyTemplatePlanner}, a DIFFERENT source
     * that picks different cells. The penalty may not punish the cells the fabricator was
     * told to place: when day-compact is armed, these cells OVERRIDE the planner's for
     * every course the menu covers (courses the menu does not cover keep the planner's).
     */
    public static Map<Long, java.util.Set<Integer>> templateCells(
            Map<StudentGroup, Map<DayOfWeek, List<DayCompactBuilder.MenuBlock>>> menu,
            List<LocalDate> schoolDates) {
        Map<Long, java.util.Set<Integer>> cellsByCourse = new LinkedHashMap<>();
        for (var groupEntry : menu.entrySet()) {
            StudentGroup g = groupEntry.getKey();
            for (LocalDate date : schoolDates) {
                DayOfWeek wd = date.getDayOfWeek();
                List<DayCompactBuilder.MenuBlock> dayMenu = groupEntry.getValue().get(wd);
                if (dayMenu == null || dayMenu.isEmpty()) {
                    continue;
                }
                int[] window = com.school.planner.domain.SchoolSchedule
                        .getGroupCalendarWindow(g.id, wd, date);
                if (window == null || window[1] < 0) {
                    continue;
                }
                DayCompactBuilder.stampDay(dayMenu, window[1], window[2],
                        new DayCompactBuilder.CellPlacer() {
                            @Override
                            public Object place(Course course, int slot) {
                                cellsByCourse.computeIfAbsent(course.id, k -> new java.util.HashSet<>())
                                        .add(com.school.planner.domain.SchoolSchedule
                                                .encodeTemplateCell(wd, slot));
                                return this; // recording placer never declines
                            }

                            @Override
                            public void undo(Object handle) {
                                // never called: place() never returns null
                            }
                        });
            }
        }
        return cellsByCourse;
    }
}
