package com.school.planner.bootstrap;

import java.nio.file.Path;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.util.HashMap;
import java.util.Map;
import java.util.TreeMap;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.Test;

import com.school.planner.util.SeedCsv;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * TASK B-side 28/08: golden-pin della BUSTA GOLDEN per (gruppo, weekday). The
 * committed artifact ({@code claudodocs/spalmone-2026-27/data/golden-weekday-
 * envelope.json}, generated by {@code scripts/analyze/golden-weekday-envelope.py})
 * must be IDENTICAL to what the live golden ({@code seed/lessons.csv}) yields when
 * re-read from Java - the same identity-gate shape as {@code GoldenCoPresenceFreezeTest}
 * (the java-reimplementation-diverges lesson: never trust a derived copy without an
 * equality gate). Consumers: the sanity gate's BUSTA section (additive there,
 * promotion to a red rule travels with the next batch's cycle) and the two golden
 * tolerances of the 28/08 mandate ("cap G12 venerdi'" = [4..5] mode 4;
 * "busta giorni-corti FC" = ordinary days [3..5] where the sheet asks 5-6).
 *
 * <p>Plain JUnit (no {@code @QuarkusTest}): pure file arithmetic - the golden CSV
 * from the classpath, the artifact from the repo tree - so it runs in the fast
 * slice and dies loudly the moment either side drifts.</p>
 */
class GoldenWeekdayEnvelopeTest {

    @SuppressWarnings("unchecked")
    @Test
    void committedEnvelopeMatchesLiveGolden() throws Exception {
        // two clean folds: hours per (group, date), then the per-(group, weekday)
        // envelope (min/max/days/sum + a count histogram for the mode)
        Map<String, Map<LocalDate, Integer>> hoursByGroupDate = new HashMap<>();
        for (String[] row : SeedCsv.load("lessons.csv", 7)) {
            // same protocol exclusions as the extractor and the sanity gate
            if ("True".equalsIgnoreCase(row[3]) || "Sabato".equals(row[1])) {
                continue;
            }
            if ("Stage".equals(row[6]) || "Fasullo".equals(row[5])) {
                continue;
            }
            LocalDate d = LocalDate.parse(row[0].trim());
            if (d.getDayOfWeek() == DayOfWeek.SATURDAY || d.getDayOfWeek() == DayOfWeek.SUNDAY) {
                continue;
            }
            hoursByGroupDate.computeIfAbsent(row[4], k -> new TreeMap<>())
                    .merge(d, 1, Integer::sum);
        }
        Map<String, Map<String, Integer>> live = new HashMap<>();
        for (var ge : hoursByGroupDate.entrySet()) {
            for (var de : ge.getValue().entrySet()) {
                int hours = de.getValue();
                Map<String, Integer> cell = live.computeIfAbsent(
                        ge.getKey() + "|" + de.getKey().getDayOfWeek().getValue(),
                        k -> new TreeMap<>());
                cell.merge("sum", hours, Integer::sum);
                cell.merge("days", 1, Integer::sum);
                cell.merge("min", hours, Math::min);
                cell.merge("max", hours, Math::max);
                cell.merge("count" + hours, 1, Integer::sum);
            }
        }
        for (Map<String, Integer> cell : live.values()) {
            // deterministic tie-break mirrored from the extractor: highest count,
            // then the SMALLEST hours value (ascending h scan keeps the first max)
            int mode = -1;
            int bestCount = -1;
            for (int h = 1; h <= 8; h++) {
                int c = cell.getOrDefault("count" + h, 0);
                if (c > bestCount) {
                    bestCount = c;
                    mode = h;
                }
            }
            cell.put("mode", mode);
        }

        Map<String, Map<String, Object>> committed = new ObjectMapper().readValue(
                Path.of("claudodocs/spalmone-2026-27/data/golden-weekday-envelope.json").toFile(),
                Map.class);
        assertEquals(live.size(), committed.size(),
                "artifact cell count drift: live golden has " + live.size() + " cells");
        for (var e : live.entrySet()) {
            Map<String, Object> cell = committed.get(e.getKey());
            assertTrue(cell != null, "envelope artifact missing cell " + e.getKey());
            for (String field : new String[] { "min", "mode", "max", "days", "sum" }) {
                assertEquals(e.getValue().get(field).intValue(),
                        ((Number) cell.get(field)).intValue(),
                        e.getKey() + " " + field + " drift vs the live golden");
            }
        }

        // pin the two mandate-named tolerances explicitly: if the golden ever
        // moves these, this pin and the registro quote must move TOGETHER, loudly
        assertEquals(4, ((Number) committed.get("G12|5").get("min")).intValue());
        assertEquals(4, ((Number) committed.get("G12|5").get("mode")).intValue());
        assertEquals(5, ((Number) committed.get("G12|5").get("max")).intValue());
        assertEquals(2, ((Number) committed.get("G08|4").get("min")).intValue());
        assertEquals(5, ((Number) committed.get("G08|4").get("mode")).intValue());
    }
}
